%% P06 - Run an FMEA
% Guiding question:
% What inputs, observable effects, and failure modes matter when you run an
% FMEA?

%% Read, then inspect the deterministic bottom-up worksheet
% P05 worked top-down from cooling loss to combinations S OR (A AND B).
% P06 follows the same fixed 1000-hour, no-repair boundary bottom-up: each
% FMEA row starts from one item function and failure mode, then traces its
% cause, local effect, next-higher effect, end effect, and indicator.
% Each effect column assumes only its row mode is present and companion
% items are available. Occurrence rows may co-occur; P05 owns their combined
% system effects.
baseline = model([0.005 0.10 0.10],[0.98 0.70 0.90]);

worksheetData = { ...
    'Item / required function',baseline.itemFunctions{1}, ...
        baseline.itemFunctions{2},baseline.itemFunctions{3}; ...
    'Failure mode',baseline.failureModes{1},baseline.failureModes{2}, ...
        baseline.failureModes{3}; ...
    'Example cause',baseline.exampleCauses{1},baseline.exampleCauses{2}, ...
        baseline.exampleCauses{3}; ...
    'Local effect',baseline.localEffects{1},baseline.localEffects{2}, ...
        baseline.localEffects{3}; ...
    'Next-higher effect',baseline.nextHigherEffects{1}, ...
        baseline.nextHigherEffects{2},baseline.nextHigherEffects{3}; ...
    'End effect',baseline.endEffects{1},baseline.endEffects{2}, ...
        baseline.endEffects{3}; ...
    'Observable effect',baseline.observableEffects{1}, ...
        baseline.observableEffects{2},baseline.observableEffects{3}; ...
    'Prevention control',baseline.preventionControls{1}, ...
        baseline.preventionControls{2},baseline.preventionControls{3}; ...
    'Detection control',baseline.detectionControls{1}, ...
        baseline.detectionControls{2},baseline.detectionControls{3}; ...
    'Consequence class',baseline.consequenceClasses{1}, ...
        baseline.consequenceClasses{2},baseline.consequenceClasses{3}; ...
    'q per 1000 h (dimensionless)',baseline.failureModeOccurrence(1), ...
        baseline.failureModeOccurrence(2),baseline.failureModeOccurrence(3); ...
    'c = P(annunciates | mode) (dimensionless)', ...
        baseline.detectionCoverage(1), ...
        baseline.detectionCoverage(2),baseline.detectionCoverage(3)};
worksheetFigure = figure('Name','P06 baseline: FMEA worksheet', ...
    'Position',[60 80 1320 700]);
uitable(worksheetFigure,'Data',worksheetData,'Units','normalized', ...
    'Position',[0.01 0.02 0.98 0.96], ...
    'ColumnName',{'FMEA field','S - Shared supply','A - Pump A','B - Pump B'}, ...
    'ColumnWidth',{180,340,340,340});
fprintf(['Baseline FMEA metrics per fixed 1000-hour mission: expected listed ' ...
    'mode occurrences = %.4f, detected = %.4f, latent = %.4f.\n'], ...
    baseline.expectedModeCount,baseline.expectedDetectedCount, ...
    baseline.expectedLatentCount);
for k = 1:baseline.modeCount
    fprintf(['Row %s: q = %.4f, coverage = %.2f, detected = %.4f, ' ...
        'latent = %.4f, end effect: %s.\n'],baseline.modeIds{k}, ...
        baseline.failureModeOccurrence(k),baseline.detectionCoverage(k), ...
        baseline.detectedOccurrence(k),baseline.latentOccurrence(k), ...
        baseline.endEffects{k});
end
disp(['Mechanism: a failure mode is how one item fails its required ' ...
    'function. The effects follow forward; the detector is evidence about ' ...
    'that mode, not the mode itself.']);
disp(['Effect premise: only the row-under-analysis mode is present and ' ...
    'companion items are available. Use P05 for combined-event effects.']);

%% Read the complementary occurrence-and-observability view
figure('Name','P06 baseline: detected and latent occurrence');
bar(1:baseline.modeCount,[baseline.failureModeOccurrence(:), ...
    baseline.detectedOccurrence(:),baseline.latentOccurrence(:)], ...
    'grouped');
grid on; xticks(1:baseline.modeCount); xticklabels(baseline.modeIds);
xlabel('FMEA failure-mode row');
ylabel('Probability per fixed 1000-hour mission (dimensionless)');
title('Each physical occurrence partitions into detected and latent paths');
legend({'Physical occurrence q','Detected q*c','Latent q*(1-c)'}, ...
    'Location','northwest');
ylim([0 0.12]);
disp(['The identity q*c + q*(1-c) = q is conditional-probability ' ...
    'accounting. It does not assume independent detectors or failure modes.']);
disp(['Sums across rows are expected mode-occurrence counts per mission, ' ...
    'not the probability of a system-level union and not a priority score.']);

%% Sweep 1 - move only pump-A occurrence probability
pumpAOccurrenceSweep = [0 0.05 0.10 0.20 0.40];
expectedModeCountOccurrenceSweep = zeros(size(pumpAOccurrenceSweep));
expectedDetectedCountOccurrenceSweep = zeros(size(pumpAOccurrenceSweep));
expectedLatentCountOccurrenceSweep = zeros(size(pumpAOccurrenceSweep));
pumpADetectedOccurrenceSweep = zeros(size(pumpAOccurrenceSweep));
pumpALatentOccurrenceSweep = zeros(size(pumpAOccurrenceSweep));
for k = 1:numel(pumpAOccurrenceSweep)
    changed = model([0.005 pumpAOccurrenceSweep(k) 0.10], ...
        [0.98 0.70 0.90]);
    expectedModeCountOccurrenceSweep(k) = changed.expectedModeCount;
    expectedDetectedCountOccurrenceSweep(k) = changed.expectedDetectedCount;
    expectedLatentCountOccurrenceSweep(k) = changed.expectedLatentCount;
    pumpADetectedOccurrenceSweep(k) = changed.detectedOccurrence(2);
    pumpALatentOccurrenceSweep(k) = changed.latentOccurrence(2);
end
figure('Name','P06 sweep 1: pump-A mode occurrence');
plot(pumpAOccurrenceSweep,expectedModeCountOccurrenceSweep,'o-', ...
    'LineWidth',1.5,'DisplayName','All listed mode occurrences'); hold on;
plot(pumpAOccurrenceSweep,expectedDetectedCountOccurrenceSweep,'s--', ...
    'LineWidth',1.4,'DisplayName','Detected occurrences');
plot(pumpAOccurrenceSweep,expectedLatentCountOccurrenceSweep,'d:', ...
    'LineWidth',1.4,'DisplayName','Latent occurrences'); hold off;
grid on;
xlabel('Pump-A occurrence probability per 1000-hour mission (dimensionless)');
ylabel('Expected listed mode occurrences per mission (count/mission)');
title('Occurrence lever scales both Pump-A observability partitions');
legend('Location','northwest');
fprintf(['Pump-A occurrence sweep detected A = [%.3f %.3f %.3f %.3f %.3f], ' ...
    'latent A = [%.3f %.3f %.3f %.3f %.3f].\n'], ...
    pumpADetectedOccurrenceSweep,pumpALatentOccurrenceSweep);
disp(['Mechanism: coverage and every effect-chain label stay fixed. ' ...
    'Increasing qA creates more detected and more latent Pump-A occurrences.']);

%% Sweep 2 - reset occurrence, then move only pump-A detection coverage
pumpADetectionCoverageSweep = [0 0.25 0.50 0.70 1];
expectedModeCountCoverageSweep = zeros(size(pumpADetectionCoverageSweep));
expectedDetectedCountCoverageSweep = zeros(size(pumpADetectionCoverageSweep));
expectedLatentCountCoverageSweep = zeros(size(pumpADetectionCoverageSweep));
pumpADetectedCoverageSweep = zeros(size(pumpADetectionCoverageSweep));
pumpALatentCoverageSweep = zeros(size(pumpADetectionCoverageSweep));
for k = 1:numel(pumpADetectionCoverageSweep)
    changed = model([0.005 0.10 0.10], ...
        [0.98 pumpADetectionCoverageSweep(k) 0.90]);
    expectedModeCountCoverageSweep(k) = changed.expectedModeCount;
    expectedDetectedCountCoverageSweep(k) = changed.expectedDetectedCount;
    expectedLatentCountCoverageSweep(k) = changed.expectedLatentCount;
    pumpADetectedCoverageSweep(k) = changed.detectedOccurrence(2);
    pumpALatentCoverageSweep(k) = changed.latentOccurrence(2);
end
figure('Name','P06 sweep 2: pump-A detection coverage');
plot(pumpADetectionCoverageSweep,expectedModeCountCoverageSweep,'o-', ...
    'LineWidth',1.5,'DisplayName','All listed mode occurrences'); hold on;
plot(pumpADetectionCoverageSweep,expectedDetectedCountCoverageSweep,'s--', ...
    'LineWidth',1.4,'DisplayName','Detected occurrences');
plot(pumpADetectionCoverageSweep,expectedLatentCountCoverageSweep,'d:', ...
    'LineWidth',1.4,'DisplayName','Latent occurrences'); hold off;
grid on; xlabel('Pump-A detection coverage P(annunciates | mode) (dimensionless)');
ylabel('Expected listed mode occurrences per mission (count/mission)');
title('Detection lever repartitions observability without changing physics');
legend('Location','best');
fprintf(['Pump-A coverage sweep total detected = ' ...
    '[%.4f %.4f %.4f %.4f %.4f], total latent = ' ...
    '[%.4f %.4f %.4f %.4f %.4f].\n'], ...
    expectedDetectedCountCoverageSweep,expectedLatentCountCoverageSweep);
disp(['Mechanism: qA remains 0.10. Better coverage transfers occurrence ' ...
    'from the latent path to the detected path; their sum does not move.']);

%% Deliberately broken case - use filtered true-positive logs as the whole inventory
brokenCase = model([0.005 0.10 0.10],[0.98 0 0.90]);
figure('Name','P06 broken case: oracle-filtered detected-only inventory');
bar(1:3,[brokenCase.failureModeOccurrence(2), ...
    brokenCase.wrongReportedOccurrence(2), ...
    brokenCase.latentOccurrence(2)],0.62);
grid on; xticks(1:3);
xticklabels({'Physical Pump-A occurrence','Wrong log-only report', ...
    'Unannunciated Pump-A occurrence'});
ylabel('Probability per fixed 1000-hour mission (dimensionless)');
title('Broken assumption: every relevant occurrence appears in filtered logs');
ylim([0 0.12]);
fprintf(['Broken-case symptom at qA = %.2f and cA = %.2f: true qA = %.2f, ' ...
    'wrong reported qA = %.2f, latent qA = %.2f.\n'], ...
    brokenCase.failureModeOccurrence(2),brokenCase.detectionCoverage(2), ...
    brokenCase.failureModeOccurrence(2), ...
    brokenCase.wrongReportedOccurrence(2), ...
    brokenCase.latentOccurrence(2));
assert(brokenCase.failureModeOccurrence(2) == 0.10 && ...
    brokenCase.wrongReportedOccurrence(2) == 0 && ...
    brokenCase.latentOccurrence(2) == 0.10, ...
    'A detector-blind Pump-A mode must remain physical and entirely latent.');
assert(abs(brokenCase.wrongUndercount-0.1101) < 1e-15, ...
    'The log-only inventory must expose its exact expected-count undercount.');
disp(['Diagnosis: the broken worksheet assumes coverage is perfect. ' ...
    'No annunciation is missing evidence, not proof that the mode vanished.']);
disp(['Logging premise: one oracle-filtered true-positive record per ' ...
    'detected occurrence, perfect specificity, and unique attribution. ' ...
    'Raw logs may additionally overcount or misattribute modes.']);
