%% P08 - Prioritize Risk Quantitatively
% Guiding question:
% What inputs, observable effects, and failure modes matter when you
% prioritize Risk Quantitatively?

%% Read the decision boundary before assigning a priority
% P06 supplied failure modes and observable effects. P07 supplied a fixed
% 1000-hour, no-repair mission and five mutually exclusive outcomes for
% independent basic events S, A, and B. P08 keeps that physical model and
% adds one synthetic common consequence unit: kUSD per scenario occurrence.
% For disjoint scenario i,
%
%       expected loss_i = P(scenario_i)*consequence_i
%
% has units kUSD per mission. The ranking is conditional on the stated
% probabilities, consequences, boundary, and independence assumption.
baseline = model([0.005 0.10 0.10],[120 100 8 12]);

%% Baseline view 1 - audit the disjoint P07 outcome probabilities
probabilityFigure = figure('Name','P08 baseline: disjoint outcome ledger');
probabilityAxes = axes('Parent',probabilityFigure);
bar(probabilityAxes,1:5,baseline.outcomeProbabilities,0.68);
grid(probabilityAxes,'on'); xticks(probabilityAxes,1:5);
xticklabels(probabilityAxes,{'S fails','A and B fail', ...
    'B fails only','A fails only','All work'});
xtickangle(probabilityAxes,15);
ylabel(probabilityAxes, ...
    ['Scenario occurrence probability per fixed 1000-hour mission ' ...
    '(dimensionless)']);
title(probabilityAxes,'P07 outcomes are mutually exclusive and close to one');
ylim(probabilityAxes,[0 1]);
fprintf(['Baseline outcome probabilities = [%.5f %.5f %.5f %.5f %.5f]; ' ...
    'mission failure = %.5f; mission success = %.5f; closure residual = %.3g.\n'], ...
    baseline.outcomeProbabilities(1), ...
    baseline.outcomeProbabilities(2),baseline.outcomeProbabilities(3), ...
    baseline.outcomeProbabilities(4),baseline.outcomeProbabilities(5), ...
    baseline.systemFailureProbability,baseline.systemReliability, ...
    baseline.probabilityClosureResidual);
disp(['Mechanism: the first four bars are disjoint loss-bearing scenarios. ' ...
    'Only the first two fail the mission; the two single-pump states are ' ...
    'degraded successes. The fifth is full success and carries no loss.']);

%% Baseline view 2 - see probability and consequence before multiplying
riskPlaneFigure = figure('Name','P08 baseline: probability-consequence plane');
riskPlaneAxes = axes('Parent',riskPlaneFigure);
markerSizes = 90+520*baseline.riskShares;
scatter(riskPlaneAxes,baseline.scenarioProbabilities, ...
    baseline.consequenceCostKusd,markerSizes,'filled');
grid(riskPlaneAxes,'on');
xlabel(riskPlaneAxes, ...
    ['Scenario occurrence probability per fixed 1000-hour mission ' ...
    '(dimensionless)']);
ylabel(riskPlaneAxes,'Consequence cost (kUSD/scenario occurrence)');
title(riskPlaneAxes,'Expected loss is probability times common-unit consequence');
xlim(riskPlaneAxes,[0 0.105]); ylim(riskPlaneAxes,[0 130]);
for k = 1:4
    text(riskPlaneAxes,baseline.scenarioProbabilities(k), ...
        baseline.consequenceCostKusd(k), ...
        sprintf('  %s',baseline.scenarioIds{k}), ...
        'VerticalAlignment','bottom');
end
disp(['A point farther right is more frequent; a point higher is more ' ...
    'costly per occurrence. Neither coordinate alone determines priority.']);

%% Baseline view 3 - rank expected loss in a common unit
rankingFigure = figure('Name','P08 baseline: expected-loss priority');
rankingAxes = axes('Parent',rankingFigure);
bar(rankingAxes,1:4,baseline.expectedLossKusdPerMission,0.68);
grid(rankingAxes,'on'); xticks(rankingAxes,1:4);
xticklabels(rankingAxes,baseline.scenarioIds);
ylabel(rankingAxes,'Expected loss (kUSD/fixed 1000-hour mission)');
title(rankingAxes,'Common-unit risk contributions can be ranked and added');
ylim(rankingAxes,[0 1.2]);
fprintf(['Baseline expected losses [S, A&B, B only, A only] = ' ...
    '[%.4f %.4f %.4f %.4f] kUSD/mission; total = %.4f.\n'], ...
    baseline.expectedLossKusdPerMission(1), ...
    baseline.expectedLossKusdPerMission(2), ...
    baseline.expectedLossKusdPerMission(3), ...
    baseline.expectedLossKusdPerMission(4), ...
    baseline.totalExpectedLossKusdPerMission);
fprintf('Priority order = [%s, %s, %s, %s].\n', ...
    baseline.scenarioIds{baseline.priorityOrder(1)}, ...
    baseline.scenarioIds{baseline.priorityOrder(2)}, ...
    baseline.scenarioIds{baseline.priorityOrder(3)}, ...
    baseline.scenarioIds{baseline.priorityOrder(4)});
disp(['Mechanism: A-only is frequent enough that its 12 kUSD consequence ' ...
    'produces the largest expected loss, ahead of rarer severe scenarios.']);

%% Sweep 1 - move only shared-supply failure probability
scenarioIds = {'S','A&B','B only','A only'};
sharedSupplyFailureProbabilitySweep = [0 0.005 0.01 0.02 0.05];
expectedLossSupplySweep = zeros(5,4);
scenarioProbabilitySupplySweep = zeros(5,4);
totalExpectedLossSupplySweep = zeros(1,5);
priorityOrderSupplySweep = zeros(5,4);
for k = 1:numel(sharedSupplyFailureProbabilitySweep)
    changed = model([sharedSupplyFailureProbabilitySweep(k) 0.10 0.10], ...
        [120 100 8 12]);
    expectedLossSupplySweep(k,:) = changed.expectedLossKusdPerMission;
    scenarioProbabilitySupplySweep(k,:) = changed.scenarioProbabilities;
    totalExpectedLossSupplySweep(k) = ...
        changed.totalExpectedLossKusdPerMission;
    priorityOrderSupplySweep(k,:) = changed.priorityOrder;
end
supplySweepFigure = figure('Name','P08 sweep 1: shared-supply occurrence');
supplySweepAxes = axes('Parent',supplySweepFigure);
colors = lines(4);
hold(supplySweepAxes,'on');
for scenarioIndex = 1:4
    plot(supplySweepAxes,sharedSupplyFailureProbabilitySweep, ...
        expectedLossSupplySweep(:,scenarioIndex),'o-', ...
        'LineWidth',1.4,'Color',colors(scenarioIndex,:), ...
        'DisplayName',scenarioIds{scenarioIndex});
end
plot(supplySweepAxes,sharedSupplyFailureProbabilitySweep, ...
    totalExpectedLossSupplySweep,'k--','LineWidth',1.7, ...
    'DisplayName','Total expected loss');
hold(supplySweepAxes,'off'); grid(supplySweepAxes,'on');
xlabel(supplySweepAxes, ...
    ['Shared-supply failure probability per fixed 1000-hour mission ' ...
    '(dimensionless)']);
ylabel(supplySweepAxes,'Expected loss (kUSD/fixed 1000-hour mission)');
title(supplySweepAxes,'Changing q_S reallocates disjoint outcome probability');
legend(supplySweepAxes,'Location','northwest');
fprintf('Supply sweep total expected loss = [%.3f %.3f %.3f %.3f %.3f].\n', ...
    totalExpectedLossSupplySweep(1),totalExpectedLossSupplySweep(2), ...
    totalExpectedLossSupplySweep(3),totalExpectedLossSupplySweep(4), ...
    totalExpectedLossSupplySweep(5));
disp(['Mechanism: increasing q_S raises the S-loss contribution but ' ...
    'slightly lowers every supply-up pump scenario because those outcomes ' ...
    'are mutually exclusive with supply failure. q_A, q_B, and every ' ...
    'consequence remain fixed.']);

%% Sweep 2 - reset probability, then move only dual-pump consequence
scenarioIds = {'S','A&B','B only','A only'};
dualPumpConsequenceSweepKusd = [0 25 50 100 200];
expectedLossConsequenceSweep = zeros(5,4);
scenarioProbabilityConsequenceSweep = zeros(5,4);
totalExpectedLossConsequenceSweep = zeros(1,5);
priorityOrderConsequenceSweep = zeros(5,4);
for k = 1:numel(dualPumpConsequenceSweepKusd)
    changed = model([0.005 0.10 0.10], ...
        [120 dualPumpConsequenceSweepKusd(k) 8 12]);
    expectedLossConsequenceSweep(k,:) = ...
        changed.expectedLossKusdPerMission;
    scenarioProbabilityConsequenceSweep(k,:) = ...
        changed.scenarioProbabilities;
    totalExpectedLossConsequenceSweep(k) = ...
        changed.totalExpectedLossKusdPerMission;
    priorityOrderConsequenceSweep(k,:) = changed.priorityOrder;
end
consequenceSweepFigure = figure('Name','P08 sweep 2: dual-pump consequence');
consequenceSweepAxes = axes('Parent',consequenceSweepFigure);
colors = lines(4);
hold(consequenceSweepAxes,'on');
for scenarioIndex = 1:4
    plot(consequenceSweepAxes,dualPumpConsequenceSweepKusd, ...
        expectedLossConsequenceSweep(:,scenarioIndex),'o-', ...
        'LineWidth',1.4,'Color',colors(scenarioIndex,:), ...
        'DisplayName',scenarioIds{scenarioIndex});
end
hold(consequenceSweepAxes,'off'); grid(consequenceSweepAxes,'on');
xlabel(consequenceSweepAxes, ...
    'Dual-pump consequence cost (kUSD/scenario occurrence)');
ylabel(consequenceSweepAxes,'Expected loss (kUSD/fixed 1000-hour mission)');
title(consequenceSweepAxes,'A consequence lever leaves every probability fixed');
legend(consequenceSweepAxes,'Location','northwest');
fprintf(['Dual-pump risk across the consequence sweep = ' ...
    '[%.5f %.5f %.5f %.5f %.5f] kUSD/mission.\n'], ...
    expectedLossConsequenceSweep(1,2), ...
    expectedLossConsequenceSweep(2,2), ...
    expectedLossConsequenceSweep(3,2), ...
    expectedLossConsequenceSweep(4,2), ...
    expectedLossConsequenceSweep(5,2));
disp(['Mechanism: the A&B scenario probability stays 0.00995. Only its ' ...
    'consequence and expected loss move; it crosses A-only at 108 kUSD.']);

%% Deliberately broken case - multiply ordinal category labels
brokenCase = model([0.005 0.10 0.10],[120 100 8 12]);
brokenFigure = figure('Name','P08 broken case: ordinal product tie');
brokenAxes = axes('Parent',brokenFigure);
bar(brokenAxes,1:4,brokenCase.wrongOrdinalProductScores,0.68);
grid(brokenAxes,'on'); xticks(brokenAxes,1:4);
xticklabels(brokenAxes,brokenCase.scenarioIds);
ylabel(brokenAxes,'Ordinal product score (no ratio-scale unit)');
title(brokenAxes,'Broken priority: four different expected losses all score 10');
ylim(brokenAxes,[0 12]);
fprintf(['Broken ordinal products = [%g %g %g %g], while expected losses ' ...
    '= [%.4f %.4f %.4f %.4f] kUSD/mission.\n'], ...
    brokenCase.wrongOrdinalProductScores(1), ...
    brokenCase.wrongOrdinalProductScores(2), ...
    brokenCase.wrongOrdinalProductScores(3), ...
    brokenCase.wrongOrdinalProductScores(4), ...
    brokenCase.expectedLossKusdPerMission(1), ...
    brokenCase.expectedLossKusdPerMission(2), ...
    brokenCase.expectedLossKusdPerMission(3), ...
    brokenCase.expectedLossKusdPerMission(4));
assert(brokenCase.wrongOrdinalScoreSpread == 0, ...
    'The deliberately broken ordinal products must retain the all-tied symptom.');
assert(abs(brokenCase.expectedLossSpreadKusdPerMission-0.4746) < 1e-12, ...
    'The common-unit expected losses must retain a recognizable spread.');
disp(['Diagnosis: category labels preserve order only. Their step sizes ' ...
    'and ratios are undefined, so multiplication cannot recover probability, ' ...
    'consequence, expected loss, or a defensible tie break.']);
