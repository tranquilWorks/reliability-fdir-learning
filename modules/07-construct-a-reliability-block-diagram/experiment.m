%% P07 - Construct a Reliability Block Diagram
% Guiding question:
% What inputs, observable effects, and failure modes matter when you
% construct a Reliability Block Diagram?

%% Read the functional boundary before drawing a block
% P06 followed three failure modes over a fixed 1000-hour, no-repair
% mission: shared supply absent (S), Pump A no flow (A), and Pump B no flow
% (B). Turn each mode around into required success. Cooling succeeds only
% when the supply works AND at least one pump works:
%
%                 S works AND (A works OR B works)
%
% An RBD is a functional success diagram, not a physical wiring sketch.
% The one shared supply therefore appears once, before the pump branches.
baseline = model(0.995,0.90,0.90);

%% Baseline view 1 - construct the success topology
topologyFigure = figure('Name','P07 baseline: correct RBD topology');
topologyAxes = axes('Parent',topologyFigure);
drawCorrectRbd(topologyAxes,baseline);
fprintf(['Baseline block reliability over the fixed 1000-hour mission: ' ...
    'R_S = %.3f, R_A = %.3f, R_B = %.3f.\n'], ...
    baseline.blockReliabilities(1),baseline.blockReliabilities(2), ...
    baseline.blockReliabilities(3));
disp(['Read from source to cooling: every success path crosses S; after S, ' ...
    'either A or B is sufficient. Series means AND, parallel means OR.']);

%% Baseline view 2 - audit mutually exclusive outcomes
ledgerFigure = figure('Name','P07 baseline: disjoint outcome ledger');
ledgerAxes = axes('Parent',ledgerFigure);
bar(ledgerAxes,1:5,baseline.outcomeProbabilities,0.68);
grid(ledgerAxes,'on'); xticks(ledgerAxes,1:5);
xticklabels(ledgerAxes,{'S fails','S works; A and B fail', ...
    'S and only A work','S and only B work','S, A, and B work'});
xtickangle(ledgerAxes,18);
ylabel(ledgerAxes, ...
    'Outcome probability per fixed 1000-hour mission (dimensionless)');
title(ledgerAxes,'Five disjoint outcomes close to one');
ylim(ledgerAxes,[0 1]);
fprintf(['Baseline R_pumps = %.5f, R_system = %.5f, Q_system = %.5f. ' ...
    'P05 top-event probability = %.5f.\n'],baseline.pumpGroupReliability, ...
    baseline.systemReliability,baseline.systemFailureProbability, ...
    1-baseline.systemReliability);
fprintf(['Success paths P(S and A) = %.5f and P(S and B) = %.5f overlap ' ...
    'by %.5f. Inclusion-exclusion gives %.5f.\n'], ...
    baseline.minimalPathReliabilities(1), ...
    baseline.minimalPathReliabilities(2), ...
    baseline.successPathOverlapProbability, ...
    baseline.inclusionExclusionReliability);
disp(['Quantification assumes independent S, A, and B block events. ' ...
    'Topology states what success requires; it does not prove independence.']);

%% Sweep 1 - move only shared-supply block reliability
sharedSupplyReliabilitySweep = [0 0.50 0.90 0.995 1];
systemReliabilitySupplySweep = zeros(size(sharedSupplyReliabilitySweep));
pumpGroupReliabilitySupplySweep = zeros(size(sharedSupplyReliabilitySweep));
systemFailureSupplySweep = zeros(size(sharedSupplyReliabilitySweep));
for k = 1:numel(sharedSupplyReliabilitySweep)
    changed = model(sharedSupplyReliabilitySweep(k),0.90,0.90);
    systemReliabilitySupplySweep(k) = changed.systemReliability;
    pumpGroupReliabilitySupplySweep(k) = changed.pumpGroupReliability;
    systemFailureSupplySweep(k) = changed.systemFailureProbability;
end
supplySweepFigure = figure('Name','P07 sweep 1: shared supply block');
supplySweepAxes = axes('Parent',supplySweepFigure);
plot(supplySweepAxes,sharedSupplyReliabilitySweep, ...
    systemReliabilitySupplySweep,'o-','LineWidth',1.5, ...
    'DisplayName','Cooling-system reliability'); hold(supplySweepAxes,'on');
plot(supplySweepAxes,sharedSupplyReliabilitySweep, ...
    pumpGroupReliabilitySupplySweep,'s--','LineWidth',1.3, ...
    'DisplayName','Parallel pump group (unchanged)');
hold(supplySweepAxes,'off'); grid(supplySweepAxes,'on');
xlabel(supplySweepAxes, ...
    'Shared-supply block reliability per fixed mission (dimensionless)');
ylabel(supplySweepAxes,'Success probability (dimensionless)');
title(supplySweepAxes,'Every valid success path requires the shared supply');
legend(supplySweepAxes,'Location','southeast'); ylim(supplySweepAxes,[0 1.02]);
fprintf(['Supply sweep R_system = [%.6f %.6f %.6f %.6f %.6f], ' ...
    'Q_system = [%.6f %.6f %.6f %.6f %.6f].\n'], ...
    systemReliabilitySupplySweep(1),systemReliabilitySupplySweep(2), ...
    systemReliabilitySupplySweep(3),systemReliabilitySupplySweep(4), ...
    systemReliabilitySupplySweep(5),systemFailureSupplySweep(1), ...
    systemFailureSupplySweep(2),systemFailureSupplySweep(3), ...
    systemFailureSupplySweep(4),systemFailureSupplySweep(5));
disp(['Mechanism: the pump group stays at 0.99. Changing R_S multiplies ' ...
    'every success path because the shared block is upstream of the split.']);

%% Sweep 2 - reset the supply, then move only Pump-A reliability
pumpAReliabilitySweep = [0 0.25 0.50 0.75 1];
systemReliabilityPumpASweep = zeros(size(pumpAReliabilitySweep));
sharedSupplyReliabilityPumpASweep = zeros(size(pumpAReliabilitySweep));
pumpBReliabilityPumpASweep = zeros(size(pumpAReliabilitySweep));
for k = 1:numel(pumpAReliabilitySweep)
    changed = model(0.995,pumpAReliabilitySweep(k),0.90);
    systemReliabilityPumpASweep(k) = changed.systemReliability;
    sharedSupplyReliabilityPumpASweep(k) = changed.blockReliabilities(1);
    pumpBReliabilityPumpASweep(k) = changed.blockReliabilities(3);
end
pumpSweepFigure = figure('Name','P07 sweep 2: Pump-A block');
pumpSweepAxes = axes('Parent',pumpSweepFigure);
plot(pumpSweepAxes,pumpAReliabilitySweep, ...
    systemReliabilityPumpASweep,'o-','LineWidth',1.5, ...
    'DisplayName','Cooling-system reliability'); hold(pumpSweepAxes,'on');
plot(pumpSweepAxes,pumpAReliabilitySweep, ...
    sharedSupplyReliabilityPumpASweep,'s--','LineWidth',1.3, ...
    'DisplayName','Shared supply (unchanged)');
plot(pumpSweepAxes,pumpAReliabilitySweep, ...
    pumpBReliabilityPumpASweep,'d:','LineWidth',1.3, ...
    'DisplayName','Pump B (unchanged)');
hold(pumpSweepAxes,'off'); grid(pumpSweepAxes,'on');
xlabel(pumpSweepAxes, ...
    'Pump-A block reliability per fixed mission (dimensionless)');
ylabel(pumpSweepAxes,'Success probability (dimensionless)');
title(pumpSweepAxes,'Pump A matters only when the parallel alternative fails');
legend(pumpSweepAxes,'Location','southeast'); ylim(pumpSweepAxes,[0 1.02]);
fprintf('Pump-A sweep R_system = [%.6f %.6f %.6f %.6f %.6f].\n', ...
    systemReliabilityPumpASweep(1),systemReliabilityPumpASweep(2), ...
    systemReliabilityPumpASweep(3),systemReliabilityPumpASweep(4), ...
    systemReliabilityPumpASweep(5));
disp(['Mechanism: R_S remains 0.995 and R_B remains 0.90. Pump A changes ' ...
    'only the branch states in which Pump B cannot carry the load.']);

%% Deliberately broken case - duplicate one shared block into two paths
brokenCase = model(0.80,0.90,0.90);
wrongFigure = figure('Name','P07 broken case: duplicated shared block');
wrongAxes = axes('Parent',wrongFigure);
drawDuplicatedSupplyRbd(wrongAxes,brokenCase);
disp(['Broken assumption: two drawings of the same physical supply have ' ...
    'been treated as two independent supplies. The S-A and S-B success ' ...
    'paths still overlap whenever the one S and both pumps work.']);

%% Observe the broken symptom, then explain the mechanism
brokenMetricFigure = figure('Name','P07 broken case: reliability symptom');
brokenMetricAxes = axes('Parent',brokenMetricFigure);
bar(brokenMetricAxes,1:3,[brokenCase.systemReliability, ...
    brokenCase.wrongIndependentPathReliability, ...
    brokenCase.rawSuccessPathSum],0.62); hold(brokenMetricAxes,'on');
plot(brokenMetricAxes,[0.5 3.5],[1 1],'k--','LineWidth',1.1, ...
    'DisplayName','Probability upper bound'); hold(brokenMetricAxes,'off');
grid(brokenMetricAxes,'on'); xticks(brokenMetricAxes,1:3);
xticklabels(brokenMetricAxes,{'Correct one-S RBD', ...
    'Wrong independent paths','Wrong raw path sum'});
ylabel(brokenMetricAxes, ...
    'Claimed mission reliability (dimensionless)');
title(brokenMetricAxes,'Shared success paths are neither disjoint nor independent');
ylim(brokenMetricAxes,[0 1.55]);
fprintf(['Broken-case symptom at R_S = 0.80: correct R = %.4f, ' ...
    'wrong independent-path R = %.4f, overstatement = %.4f, ' ...
    'raw path sum = %.4f.\n'],brokenCase.systemReliability, ...
    brokenCase.wrongIndependentPathReliability, ...
    brokenCase.wrongReliabilityOverstatement, ...
    brokenCase.rawSuccessPathSum);
assert(abs(brokenCase.systemReliability-0.7920) < 1e-15, ...
    'The correct stressed RBD reference must remain 0.7920.');
assert(abs(brokenCase.wrongIndependentPathReliability-0.9216) < 1e-15, ...
    'Duplicating the shared supply must retain the recognizable 0.9216 symptom.');
assert(brokenCase.rawSuccessPathSum > 1, ...
    'Blindly adding overlapping success paths must exceed one here.');
disp(['Diagnosis: keep each physical success event as one block, then use ' ...
    'inclusion-exclusion or a disjoint outcome ledger for overlapping paths.']);

function drawCorrectRbd(axesHandle,out)
cla(axesHandle,'reset'); hold(axesHandle,'on');
plot(axesHandle,[0.5 1.2],[0 0],'k-','LineWidth',1.5);
drawBlock(axesHandle,1.2,-0.55,1.8,1.1, ...
    sprintf('S: supply works\nR_S = %.3f',out.blockReliabilities(1)), ...
    [0.86 0.92 1.00]);
plot(axesHandle,[3.0 4.0],[0 0],'k-','LineWidth',1.5);
plot(axesHandle,[4.0 4.0],[-1.5 1.5],'k-','LineWidth',1.5);
plot(axesHandle,[4.0 4.8],[1.5 1.5],'k-','LineWidth',1.5);
plot(axesHandle,[4.0 4.8],[-1.5 -1.5],'k-','LineWidth',1.5);
drawBlock(axesHandle,4.8,0.95,1.8,1.1, ...
    sprintf('A: Pump A works\nR_A = %.3f',out.blockReliabilities(2)), ...
    [0.90 0.96 0.86]);
drawBlock(axesHandle,4.8,-2.05,1.8,1.1, ...
    sprintf('B: Pump B works\nR_B = %.3f',out.blockReliabilities(3)), ...
    [0.90 0.96 0.86]);
plot(axesHandle,[6.6 7.5],[1.5 1.5],'k-','LineWidth',1.5);
plot(axesHandle,[6.6 7.5],[-1.5 -1.5],'k-','LineWidth',1.5);
plot(axesHandle,[7.5 7.5],[-1.5 1.5],'k-','LineWidth',1.5);
plot(axesHandle,[7.5 8.7],[0 0],'k-','LineWidth',1.5);
text(axesHandle,0.45,0,'SOURCE','HorizontalAlignment','right');
text(axesHandle,8.75,0,'COOLING','HorizontalAlignment','left');
text(axesHandle,4.0,2.25,'split: either pump may succeed', ...
    'HorizontalAlignment','center');
text(axesHandle,4.9,-2.65, ...
    sprintf('R_{system} = R_S[R_A + (1-R_A)R_B] = %.5f', ...
    out.systemReliability),'HorizontalAlignment','center', ...
    'Interpreter','tex','FontWeight','bold');
axis(axesHandle,[0 9.6 -3 3]); axis(axesHandle,'off');
title(axesHandle,'Correct functional topology: S AND (A OR B)');
hold(axesHandle,'off');
end

function drawDuplicatedSupplyRbd(axesHandle,out)
cla(axesHandle,'reset'); hold(axesHandle,'on');
plot(axesHandle,[0.5 1.2],[0 0],'k-','LineWidth',1.5);
plot(axesHandle,[1.2 1.2],[-1.5 1.5],'k-','LineWidth',1.5);
plot(axesHandle,[1.2 1.7],[1.5 1.5],'k-','LineWidth',1.5);
plot(axesHandle,[1.2 1.7],[-1.5 -1.5],'k-','LineWidth',1.5);
drawBlock(axesHandle,1.7,0.95,1.7,1.1, ...
    sprintf('S draw 1\nR_S = %.2f',out.blockReliabilities(1)), ...
    [1.00 0.88 0.82]);
drawBlock(axesHandle,1.7,-2.05,1.7,1.1, ...
    sprintf('S draw 2\nR_S = %.2f',out.blockReliabilities(1)), ...
    [1.00 0.88 0.82]);
plot(axesHandle,[3.4 4.0],[1.5 1.5],'k-','LineWidth',1.5);
plot(axesHandle,[3.4 4.0],[-1.5 -1.5],'k-','LineWidth',1.5);
drawBlock(axesHandle,4.0,0.95,1.7,1.1,'A: Pump A works', ...
    [0.90 0.96 0.86]);
drawBlock(axesHandle,4.0,-2.05,1.7,1.1,'B: Pump B works', ...
    [0.90 0.96 0.86]);
plot(axesHandle,[5.7 6.5],[1.5 1.5],'k-','LineWidth',1.5);
plot(axesHandle,[5.7 6.5],[-1.5 -1.5],'k-','LineWidth',1.5);
plot(axesHandle,[6.5 6.5],[-1.5 1.5],'k-','LineWidth',1.5);
plot(axesHandle,[6.5 7.6],[0 0],'k-','LineWidth',1.5);
text(axesHandle,0.45,0,'SOURCE','HorizontalAlignment','right');
text(axesHandle,7.65,0,'COOLING','HorizontalAlignment','left');
text(axesHandle,4.0,2.45, ...
    'WRONG: two drawings are treated as independent supplies', ...
    'HorizontalAlignment','center','Color',[0.75 0.05 0.05], ...
    'FontWeight','bold');
text(axesHandle,4.0,-2.75, ...
    sprintf('wrong R = %.4f; correct one-S R = %.4f', ...
    out.wrongIndependentPathReliability,out.systemReliability), ...
    'HorizontalAlignment','center','FontWeight','bold');
axis(axesHandle,[0 8.4 -3.2 3]); axis(axesHandle,'off');
title(axesHandle,'Deliberately broken RBD: one shared event has been cloned');
hold(axesHandle,'off');
end

function drawBlock(axesHandle,x,y,width,height,label,color)
rectangle('Parent',axesHandle,'Position',[x y width height], ...
    'FaceColor',color,'EdgeColor',[0.15 0.15 0.15],'LineWidth',1.3);
text(axesHandle,x+width/2,y+height/2,label, ...
    'HorizontalAlignment','center','VerticalAlignment','middle', ...
    'Interpreter','tex');
end
