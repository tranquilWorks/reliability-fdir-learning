function out = model(failureRatePerHour,meanRepairTimeHours,missionHours,sampleCount,initialAvailability)
%MODEL Compute point availability for a two-state repairable item.
%   Failure moves probability from up to down at rate lambda. Repair moves
%   probability from down to up at rate mu=1/MTTR. The solution is
%   A(t)=A_inf+(A(0)-A_inf)*exp(-(lambda+mu)*t).
arguments
    failureRatePerHour (1,1) double = 1e-3
    meanRepairTimeHours (1,1) double = 10
    missionHours (1,1) double = 100
    sampleCount (1,1) double = 601
    initialAvailability (1,1) double = 1
end

validateattributes(failureRatePerHour,{'double'}, ...
    {'real','finite','nonnegative','<=',1e6},mfilename,'failureRatePerHour');
validateattributes(meanRepairTimeHours,{'double'}, ...
    {'real','finite','>=',1e-6,'<=',1e9},mfilename,'meanRepairTimeHours');
validateattributes(missionHours,{'double'}, ...
    {'real','finite','>=',1e-6,'<=',1e9},mfilename,'missionHours');
validateattributes(sampleCount,{'double'}, ...
    {'real','finite','integer','>=',2,'<=',10000},mfilename,'sampleCount');
validateattributes(initialAvailability,{'double'}, ...
    {'real','finite','>=',0,'<=',1},mfilename,'initialAvailability');

repairRatePerHour = 1/meanRepairTimeHours;
transitionRatePerHour = failureRatePerHour+repairRatePerHour;
failureToRepairRatio = failureRatePerHour*meanRepairTimeHours;
steadyAvailability = 1/(1+failureToRepairRatio);
steadyUnavailability = failureToRepairRatio/(1+failureToRepairRatio);
relaxationTimeHours = 1/transitionRatePerHour;

timeHours = linspace(0,missionHours,sampleCount);
% Keep both weights: expm1 retains tiny transitions and exp retains tiny
% residuals after the state probabilities are close to equilibrium.
equilibriumProgress = -expm1(-transitionRatePerHour*timeHours);
equilibriumRemainder = exp(-transitionRatePerHour*timeHours);
availabilityProbability = steadyAvailability*equilibriumProgress + ...
    initialAvailability*equilibriumRemainder;
initialUnavailability = 1-initialAvailability;
unavailabilityProbability = steadyUnavailability*equilibriumProgress + ...
    initialUnavailability*equilibriumRemainder;
failureTransitionFlowPerHour = failureRatePerHour*availabilityProbability;
repairTransitionFlowPerHour = repairRatePerHour*unavailabilityProbability;
netAvailabilityFlowPerHour = repairTransitionFlowPerHour- ...
    failureTransitionFlowPerHour;

out = struct( ...
    'timeHours',timeHours, ...
    'availabilityProbability',availabilityProbability, ...
    'unavailabilityProbability',unavailabilityProbability, ...
    'failureTransitionFlowPerHour',failureTransitionFlowPerHour, ...
    'repairTransitionFlowPerHour',repairTransitionFlowPerHour, ...
    'netAvailabilityFlowPerHour',netAvailabilityFlowPerHour, ...
    'failureRatePerHour',failureRatePerHour, ...
    'meanRepairTimeHours',meanRepairTimeHours, ...
    'repairRatePerHour',repairRatePerHour, ...
    'transitionRatePerHour',transitionRatePerHour, ...
    'failureToRepairRatio',failureToRepairRatio, ...
    'steadyAvailability',steadyAvailability, ...
    'steadyUnavailability',steadyUnavailability, ...
    'steadyExpectedDowntimeHoursPerYear',8760*steadyUnavailability, ...
    'relaxationTimeHours',relaxationTimeHours, ...
    'endpointAvailability',availabilityProbability(end), ...
    'endpointUnavailability',unavailabilityProbability(end), ...
    'missionHours',missionHours, ...
    'sampleCount',sampleCount, ...
    'initialAvailability',initialAvailability);
end
