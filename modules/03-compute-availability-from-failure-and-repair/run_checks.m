function run_checks
%RUN_CHECKS Check P03 equations, limits, malformed inputs, and bounds.
baseline = model(1e-3,10,100,601,1);
repeat = model(1e-3,10,100,601,1);
assert(isequal(baseline,repeat),'Identical inputs must produce identical outputs.');

assert(baseline.timeHours(1) == 0 && baseline.timeHours(end) == 100, ...
    'The time grid must include both observation endpoints.');
assert(baseline.availabilityProbability(1) == 1, ...
    'An initially up item must start with availability one.');
assert(baseline.unavailabilityProbability(1) == 0, ...
    'An initially up item must start with unavailability zero.');
assert(baseline.endpointAvailability == baseline.availabilityProbability(end), ...
    'Endpoint point availability must equal the last availability sample.');
assert(baseline.endpointUnavailability == baseline.unavailabilityProbability(end), ...
    'Endpoint point unavailability must equal the last unavailability sample.');
assert(all(size(baseline.timeHours) == size(baseline.availabilityProbability)) && ...
    all(size(baseline.timeHours) == size(baseline.failureTransitionFlowPerHour)), ...
    'All histories must share one bounded time grid.');
assert(all(baseline.availabilityProbability >= 0 & ...
    baseline.availabilityProbability <= 1), ...
    'Availability must remain in [0,1].');
assert(all(baseline.unavailabilityProbability >= 0 & ...
    baseline.unavailabilityProbability <= 1), ...
    'Unavailability must remain in [0,1].');
assert(max(abs(baseline.availabilityProbability + ...
    baseline.unavailabilityProbability - 1)) < 1e-14, ...
    'Available and unavailable state probabilities must be complementary.');
assert(all(diff(baseline.availabilityProbability) <= 10*eps), ...
    'An initially up item must relax downward toward its balance.');

expectedRepairRate = 1/10;
expectedSteadyAvailability = expectedRepairRate/(1e-3+expectedRepairRate);
expectedSteadyUnavailability = 1-expectedSteadyAvailability;
expectedAvailability = expectedSteadyAvailability + ...
    (1-expectedSteadyAvailability)*exp(-(1e-3+expectedRepairRate)* ...
    baseline.timeHours);
assert(abs(baseline.repairRatePerHour-expectedRepairRate) < 1e-15, ...
    'Repair rate must be the reciprocal of MTTR.');
assert(abs(baseline.steadyAvailability-expectedSteadyAvailability) < 1e-14, ...
    'A_inf must independently equal mu/(lambda+mu).');
assert(abs(baseline.steadyUnavailability-expectedSteadyUnavailability) < 1e-14, ...
    'U_inf must independently equal lambda/(lambda+mu).');
assert(max(abs(baseline.availabilityProbability-expectedAvailability)) < 1e-14, ...
    'The closed-form two-state transient must hold.');
assert(abs(1e-3*baseline.steadyAvailability- ...
    expectedRepairRate*baseline.steadyUnavailability) < 1e-15, ...
    'Failure and repair transition flows must balance at steady state.');
assert(abs(baseline.steadyExpectedDowntimeHoursPerYear- ...
    8760*expectedSteadyUnavailability) < 1e-12, ...
    'Expected annual downtime must be 8760 times steady unavailability.');

lowerFailure = model(5e-4,10,100,601,1);
higherFailure = model(5e-3,10,100,601,1);
assert(higherFailure.steadyAvailability < lowerFailure.steadyAvailability, ...
    'A larger failure rate must lower steady availability when MTTR is fixed.');
assert(higherFailure.steadyExpectedDowntimeHoursPerYear > ...
    lowerFailure.steadyExpectedDowntimeHoursPerYear, ...
    'A larger failure rate must increase expected downtime when MTTR is fixed.');
shortRepair = model(1e-3,2,100,601,1);
longRepair = model(1e-3,40,100,601,1);
assert(longRepair.steadyAvailability < shortRepair.steadyAvailability, ...
    'A longer MTTR must lower steady availability when failure rate is fixed.');
assert(longRepair.steadyExpectedDowntimeHoursPerYear > ...
    shortRepair.steadyExpectedDowntimeHoursPerYear, ...
    'A longer MTTR must increase expected annual downtime.');

zeroFailureUp = model(0,10,100,601,1);
assert(max(abs(zeroFailureUp.availabilityProbability-1)) <= 10*eps, ...
    'Zero failure rate with an initially up item must give certain availability.');
zeroFailureDown = model(0,10,100,601,0);
expectedRecovery = -expm1(-zeroFailureDown.timeHours/10);
assert(max(abs(zeroFailureDown.availabilityProbability-expectedRecovery)) < 1e-14, ...
    'An initially down item with zero failure rate must recover as 1-exp(-mu*t).');
assert(all(diff(zeroFailureDown.availabilityProbability) >= -10*eps), ...
    'Initial-state recovery must move availability upward toward one.');

initiallyDown = model(1e-3,10,100,601,0);
assert(initiallyDown.availabilityProbability(1) == 0, ...
    'An initially down item must start with availability zero.');
assert(all(diff(initiallyDown.availabilityProbability) >= -10*eps), ...
    'Positive repair flow must move an initially down item upward toward balance.');
assert(initiallyDown.steadyAvailability == baseline.steadyAvailability, ...
    'The initial state must not change the rate-derived steady availability.');
assert(baseline.endpointAvailability > baseline.steadyAvailability && ...
    initiallyDown.endpointAvailability < initiallyDown.steadyAvailability, ...
    'Initially up and down trajectories must approach one balance from opposite sides.');
assert(baseline.netAvailabilityFlowPerHour(1) < 0 && ...
    initiallyDown.netAvailabilityFlowPerHour(1) > 0, ...
    'Net availability flow must point toward the common steady balance.');
tinyTime = model(1e-12,10,1e-6,3,1);
assert(tinyTime.endpointUnavailability > 0 && ...
    abs(tinyTime.endpointUnavailability/1e-18-1) < 1e-6, ...
    'Tiny-time unavailability must survive numerical cancellation.');

extremeEquilibrium = model(1e6,1e9,100,2,1);
assert(extremeEquilibrium.endpointAvailability == ...
    extremeEquilibrium.steadyAvailability && ...
    extremeEquilibrium.endpointUnavailability == ...
    extremeEquilibrium.steadyUnavailability, ...
    'A fully decayed extreme-domain transient must retain its equilibrium probabilities.');
extremeFlowScale = max(extremeEquilibrium.failureTransitionFlowPerHour(end), ...
    extremeEquilibrium.repairTransitionFlowPerHour(end));
assert(abs(extremeEquilibrium.netAvailabilityFlowPerHour(end)) <= ...
    10*eps*extremeFlowScale, ...
    'Extreme-domain failure and repair flows must balance at equilibrium.');
extremeRepairEquilibrium = model(1e-9,1e-6,100,2,0);
assert(extremeRepairEquilibrium.endpointAvailability == ...
    extremeRepairEquilibrium.steadyAvailability && ...
    extremeRepairEquilibrium.endpointUnavailability == ...
    extremeRepairEquilibrium.steadyUnavailability, ...
    'Extreme-domain recovery must retain a tiny equilibrium unavailability.');

equalRates = model(0.1,10,100,601,1);
assert(abs(equalRates.steadyAvailability-0.5) < 1e-15, ...
    'Equal failure and repair rates must give A_inf=0.5.');
sameRatioSlow = model(1e-3,10,100,601,1);
sameRatioFast = model(2e-3,5,100,601,1);
assert(abs(sameRatioSlow.steadyAvailability-sameRatioFast.steadyAvailability) < 1e-15, ...
    'Equal lambda*MTTR must preserve steady availability.');
assert(sameRatioFast.relaxationTimeHours < sameRatioSlow.relaxationTimeHours, ...
    'Equal steady availability need not imply equal relaxation time.');

nearNoRepair = model(1e-3,1e9,1000,601,1);
p02NoRepairSurvival = exp(-1e-3*nearNoRepair.timeHours);
assert(max(abs(nearNoRepair.availabilityProbability-p02NoRepairSurvival)) < 1e-6, ...
    'As repair vanishes, availability must approach the P02 no-repair survival law.');

brokenCase = model(1e-3,10,5000,1001,1);
brokenReliabilityAsAvailability = exp( ...
    -brokenCase.failureRatePerHour*brokenCase.timeHours);
assert(brokenReliabilityAsAvailability(end) < 0.01, ...
    'The broken no-repair curve must expose near-zero long-horizon reliability.');
assert(brokenCase.endpointAvailability > 0.98, ...
    'Correct repairable availability must retain its positive state balance.');
assert(brokenCase.endpointAvailability-brokenReliabilityAsAvailability(end) > 0.98, ...
    'The broken case must expose a recognizable reliability-availability gap.');

assertRejects(@() model(-1e-3,10,100,601,1), ...
    'Negative failure rate must be rejected.');
assertRejects(@() model(NaN,10,100,601,1), ...
    'A nonfinite failure rate must be rejected.');
assertRejects(@() model(Inf,10,100,601,1), ...
    'An infinite failure rate must be rejected.');
assertRejects(@() model(1i,10,100,601,1), ...
    'A complex failure rate must be rejected.');
assertRejects(@() model([1e-3 2e-3],10,100,601,1), ...
    'A nonscalar failure rate must be rejected.');
assertRejects(@() model(1e6+1,10,100,601,1), ...
    'Failure rate beyond the finite calculation domain must be rejected.');
assertRejects(@() model(1e-3,0,100,601,1), ...
    'Zero MTTR must be rejected.');
assertRejects(@() model(1e-3,NaN,100,601,1), ...
    'A nonfinite MTTR must be rejected.');
assertRejects(@() model(1e-3,1e-7,100,601,1), ...
    'MTTR below the finite calculation domain must be rejected.');
assertRejects(@() model(1e-3,1e9+1,100,601,1), ...
    'MTTR beyond the finite calculation domain must be rejected.');
assertRejects(@() model(1e-3,10,0,601,1), ...
    'A zero observation horizon must be rejected.');
assertRejects(@() model(1e-3,10,1i,601,1), ...
    'A complex observation horizon must be rejected.');
assertRejects(@() model(1e-3,10,1e9+1,601,1), ...
    'Observation horizon beyond the finite calculation domain must be rejected.');
assertRejects(@() model(1e-3,10,100,1,1), ...
    'Too few samples must be rejected.');
assertRejects(@() model(1e-3,10,100,2.5,1), ...
    'A fractional sample count must be rejected.');
assertRejects(@() model(1e-3,10,100,10001,1), ...
    'The declared sample resource bound must be enforced.');
assertRejects(@() model(1e-3,10,100,601,-0.1), ...
    'Initial availability below zero must be rejected.');
assertRejects(@() model(1e-3,10,100,601,NaN), ...
    'A nonfinite initial availability must be rejected.');
assertRejects(@() model(1e-3,10,100,601,1.1), ...
    'Initial availability above one must be rejected.');

bounded = model(1e-3,10,100,10000,0.5);
assert(numel(bounded.timeHours) == 10000, ...
    'The maximum supported sample count must remain usable and exact.');
assert(abs(bounded.initialAvailability-0.5) < eps, ...
    'A bounded ensemble initial probability must remain supported.');
disp(['P03 checks passed. Explain why no-first-failure reliability is not ' ...
    'repairable availability before claiming completion.']);
end

function assertRejects(operation,message)
didReject = false;
try
    operation();
catch
    didReject = true;
end
assert(didReject,message);
end
