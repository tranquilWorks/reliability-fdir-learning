%% P04 - Expose Common-Cause Failure
% Guiding question:
% What inputs, observable effects, and failure modes matter when you expose
% Common-Cause Failure?

%% Read, then visualize the deterministic baseline
% P03 separated failure rate from repairable availability. P04 deliberately
% returns to no-repair mission reliability so dependence is the only new
% mechanism. Each channel keeps marginal hazard lambda, split into a shared
% all-channel hazard beta*lambda and an independent hazard (1-beta)*lambda.
baseline = model(1e-4,0.05,2,1000,601);

figure('Name','P04 baseline: dependence changes joint reliability');
plot(baseline.timeHours,baseline.systemReliability,'LineWidth',1.5, ...
    'DisplayName','Correct: shared + independent hazards'); hold on;
plot(baseline.timeHours,baseline.assumedIndependentSystemReliability,'--', ...
    'LineWidth',1.4,'DisplayName','Assumed independent channels');
plot(baseline.timeHours,baseline.marginalChannelSurvivalProbability,':', ...
    'LineWidth',1.4,'DisplayName','One channel (same marginal hazard)'); hold off;
grid on; ylim([0.88 1.002]); xlabel('Mission time (h)');
ylabel('Reliability probability');
title('Observable: dependence lowers redundant-group reliability');
legend('Location','best');

fprintf(['Baseline metrics: lambda = %.4g /h, beta = %.3f, channels = %d, ' ...
    'lambda_c = %.4g /h, lambda_i = %.4g /h, R(T) = %.8f, ' ...
    'Q_common(T) = %.8f, Q_independent(T) = %.8f, ' ...
    'Q_assumed(T) = %.8f\n'],baseline.channelFailureRatePerHour, ...
    baseline.commonCauseFraction,baseline.channelCount, ...
    baseline.commonCauseRatePerHour,baseline.independentFailureRatePerHour, ...
    baseline.endpointSystemReliability, ...
    baseline.endpointCommonCauseEventProbability, ...
    baseline.endpointIndependentExhaustionProbability, ...
    baseline.endpointAssumedIndependentFailureProbability);

%% Read the baseline mechanism in one complementary view
figure('Name','P04 baseline mechanism: failure-mode decomposition');
plot(baseline.timeHours,baseline.systemFailureProbability,'LineWidth',1.5, ...
    'DisplayName','Total system failure Q(t)'); hold on;
plot(baseline.timeHours,baseline.commonCauseEventProbability,'--', ...
    'LineWidth',1.4,'DisplayName','Shared event occurred');
plot(baseline.timeHours,baseline.independentExhaustionProbability,':', ...
    'LineWidth',1.5,'DisplayName','No shared event; both independent modes failed');
hold off; grid on; xlabel('Mission time (h)');
ylabel('System failure probability');
title('Mechanism: mutually exclusive failure terms add to Q(t)');
legend('Location','best');
disp(['Mechanism: beta moves part of each channel hazard into one shared ' ...
    'event. Extra channels reduce only the independent-exhaustion term; ' ...
    'they cannot divide away the shared-event term.']);

%% Sweep 1 - move only the common-cause-fraction lever
commonCauseFractionSweep = [0 0.01 0.05 0.2];
figure('Name','P04 sweep 1: common-cause fraction'); hold on; grid on;
for k = 1:numel(commonCauseFractionSweep)
    changed = model(1e-4,commonCauseFractionSweep(k),2,1000,601);
    plot(changed.timeHours,changed.systemFailureProbability,'LineWidth',1.3, ...
        'DisplayName',sprintf('beta = %.2f',commonCauseFractionSweep(k)));
end
xlabel('Mission time (h)'); ylabel('System failure probability Q(t)');
title('More shared hazard defeats more of the two-channel benefit');
legend('Location','best');
disp(['Mechanism: lambda, channel count, and mission time stay fixed. ' ...
    'Increasing beta preserves one-channel reliability but makes the two ' ...
    'channel outcomes more dependent.']);

%% Sweep 2 - reset, then move only the channel-count lever
channelCountSweep = [1 2 3 4 6];
endpointFailureSweep = zeros(size(channelCountSweep));
endpointAssumedFailureSweep = zeros(size(channelCountSweep));
endpointCommonCauseFloor = zeros(size(channelCountSweep));
for k = 1:numel(channelCountSweep)
    changed = model(1e-4,0.05,channelCountSweep(k),1000,601);
    endpointFailureSweep(k) = changed.endpointSystemFailureProbability;
    endpointAssumedFailureSweep(k) = ...
        changed.endpointAssumedIndependentFailureProbability;
    endpointCommonCauseFloor(k) = changed.endpointCommonCauseEventProbability;
end
figure('Name','P04 sweep 2: channel count');
semilogy(channelCountSweep,endpointFailureSweep,'o-','LineWidth',1.5, ...
    'MarkerFaceColor',[0.2 0.45 0.75], ...
    'DisplayName','Correct beta-factor Q(T)'); hold on;
semilogy(channelCountSweep,endpointAssumedFailureSweep,'s--','LineWidth',1.3, ...
    'DisplayName','Assumed independent Q(T)');
semilogy(channelCountSweep,endpointCommonCauseFloor,':','LineWidth',1.5, ...
    'DisplayName','Shared-event contribution'); hold off;
grid on; xlabel('Channels in one-out-of-n redundant group');
ylabel('Mission failure probability Q(T)');
title('Extra channels remove independent risk but approach shared risk');
legend('Location','best');
fprintf(['Channel sweep metrics at T = 1000 h: correct Q(T) = ' ...
    '[%.8g %.8g %.8g %.8g %.8g]\n'],endpointFailureSweep(1), ...
    endpointFailureSweep(2),endpointFailureSweep(3), ...
    endpointFailureSweep(4),endpointFailureSweep(5));
disp(['Mechanism: beta and marginal channel hazard stay fixed. Each extra ' ...
    'channel makes simultaneous independent exhaustion less likely, while ' ...
    'the all-channel shared-event contribution stays unchanged.']);

%% Deliberately broken case - multiply marginal failures as independent
brokenCase = model(1e-4,0.05,6,1000,601);
optimismFactor = brokenCase.endpointSystemFailureProbability/ ...
    brokenCase.endpointAssumedIndependentFailureProbability;
visibleSamples = 2:numel(brokenCase.timeHours);

figure('Name','P04 broken case: nominal redundancy hides shared risk');
semilogy(brokenCase.timeHours(visibleSamples), ...
    brokenCase.systemFailureProbability(visibleSamples),'LineWidth',1.5, ...
    'DisplayName','Correct: shared + independent failure'); hold on;
semilogy(brokenCase.timeHours(visibleSamples), ...
    brokenCase.assumedIndependentSystemFailureProbability(visibleSamples), ...
    '--','LineWidth',1.5,'DisplayName','Broken: multiply marginal failures');
semilogy(brokenCase.timeHours(visibleSamples), ...
    brokenCase.commonCauseEventProbability(visibleSamples),':', ...
    'LineWidth',1.5,'DisplayName','Shared-event contribution'); hold off;
grid on; xlabel('Mission time (h)'); ylabel('System failure probability');
title('Broken assumption: six channels do not create six independent outcomes');
legend('Location','best');

fprintf(['Broken-case symptom at 1000 h: correct Q = %.8g, independence ' ...
    'claim Q = %.8g, optimism factor = %.1f.\n'], ...
    brokenCase.endpointSystemFailureProbability, ...
    brokenCase.endpointAssumedIndependentFailureProbability,optimismFactor);
assert(optimismFactor > 1000, ...
    'The broken independence claim should be recognizably optimistic.');
assert(brokenCase.endpointCommonCauseEventProbability > ...
    brokenCase.endpointAssumedIndependentFailureProbability, ...
    'The shared-event contribution should exceed the broken six-channel estimate.');
