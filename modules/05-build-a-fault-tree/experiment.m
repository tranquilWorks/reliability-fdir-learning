%% P05 - Build a Fault Tree
% Guiding question:
% What inputs, observable effects, and failure modes matter when you build a
% Fault Tree?

%% Read, then visualize the deterministic fault-tree baseline
% P04 separated a shared event from channel-specific failures. Here the top
% event is loss of cooling over one fixed 1000-hour no-repair mission:
% T = S OR (A AND B). S, A, and B are independent basic events here.
baseline = model(0.005,0.10,0.10);

figure('Name','P05 baseline: fault-tree structure');
treeAxes = axes;
drawFaultTree(treeAxes,baseline);
fprintf(['Baseline metrics per 1000-hour mission: qS = %.5f, qA = %.5f, qB = %.5f, ' ...
    'P({A,B}) = %.5f, Q_top = %.5f, cooling available = %.5f\n'], ...
    baseline.sharedSupplyFailureProbability, ...
    baseline.pumpAFailureProbability,baseline.pumpBFailureProbability, ...
    baseline.dualPumpCutSetProbability,baseline.topEventProbability, ...
    baseline.coolingAvailableProbability);

%% Read the same baseline in one complementary probability view
figure('Name','P05 baseline mechanism: disjoint contributions');
bar(1:3,[baseline.sharedExclusiveContribution, ...
    baseline.dualPumpExclusiveContribution,baseline.topEventProbability], ...
    0.62);
grid on; xticks(1:3);
xticklabels({'S occurs','No S; A and B occur','Exact top event'});
ylabel('Event probability per mission (dimensionless)');
title('Mechanism: non-overlapping paths add to loss of cooling');
ylim([0 1.18*baseline.topEventProbability]);
fprintf(['Disjoint contributions: shared = %.5f, no-shared/dual-pump = ' ...
    '%.5f, exact sum = %.5f. Raw cut-set sum = %.5f.\n'], ...
    baseline.sharedExclusiveContribution, ...
    baseline.dualPumpExclusiveContribution,baseline.topEventProbability, ...
    baseline.cutSetProbabilitySum);
disp(['Mechanism: {S} reaches the top event alone. {A,B} reaches it only ' ...
    'when both pump-specific events occur while the shared supply remains available.']);

%% Sweep 1 - move only the shared-supply probability lever
sharedSupplyProbabilitySweep = [0 0.005 0.02 0.05];
topEventSharedSweep = zeros(size(sharedSupplyProbabilitySweep));
sharedContributionSweep = zeros(size(sharedSupplyProbabilitySweep));
dualPumpContributionSharedSweep = zeros(size(sharedSupplyProbabilitySweep));
for k = 1:numel(sharedSupplyProbabilitySweep)
    changed = model(sharedSupplyProbabilitySweep(k),0.10,0.10);
    topEventSharedSweep(k) = changed.topEventProbability;
    sharedContributionSweep(k) = changed.sharedExclusiveContribution;
    dualPumpContributionSharedSweep(k) = ...
        changed.dualPumpExclusiveContribution;
end
figure('Name','P05 sweep 1: shared-supply basic event');
plot(sharedSupplyProbabilitySweep,topEventSharedSweep,'o-', ...
    'LineWidth',1.5,'MarkerFaceColor',[0.2 0.45 0.75], ...
    'DisplayName','Exact top event'); hold on;
plot(sharedSupplyProbabilitySweep,sharedContributionSweep,'s--', ...
    'LineWidth',1.4,'DisplayName','Singleton cut set {S}');
plot(sharedSupplyProbabilitySweep,dualPumpContributionSharedSweep,'d:', ...
    'LineWidth',1.4,'DisplayName','No S; A and B occur'); hold off;
grid on; xlabel('Shared-supply failure probability per mission (dimensionless)');
ylabel('Event probability per mission (dimensionless)');
title('Shared-supply lever acts directly through singleton cut set {S}');
legend('Location','best');
fprintf(['Shared-supply sweep Q_top = [%.5f %.5f %.5f %.5f]\n'], ...
    topEventSharedSweep(1),topEventSharedSweep(2), ...
    topEventSharedSweep(3),topEventSharedSweep(4));
disp(['Mechanism: qA and qB stay at 0.10. Increasing qS raises the direct ' ...
    'shared path while slightly reducing the mutually exclusive no-S path.']);

%% Sweep 2 - reset, then move only the pump-A probability lever
pumpAFailureProbabilitySweep = [0 0.05 0.10 0.20 0.40];
topEventPumpASweep = zeros(size(pumpAFailureProbabilitySweep));
sharedContributionPumpASweep = zeros(size(pumpAFailureProbabilitySweep));
dualPumpContributionPumpASweep = zeros(size(pumpAFailureProbabilitySweep));
for k = 1:numel(pumpAFailureProbabilitySweep)
    changed = model(0.005,pumpAFailureProbabilitySweep(k),0.10);
    topEventPumpASweep(k) = changed.topEventProbability;
    sharedContributionPumpASweep(k) = changed.sharedExclusiveContribution;
    dualPumpContributionPumpASweep(k) = ...
        changed.dualPumpExclusiveContribution;
end
figure('Name','P05 sweep 2: pump-A basic event');
plot(pumpAFailureProbabilitySweep,topEventPumpASweep,'o-', ...
    'LineWidth',1.5,'MarkerFaceColor',[0.75 0.35 0.2], ...
    'DisplayName','Exact top event'); hold on;
plot(pumpAFailureProbabilitySweep,sharedContributionPumpASweep,'s--', ...
    'LineWidth',1.4,'DisplayName','Shared contribution');
plot(pumpAFailureProbabilitySweep,dualPumpContributionPumpASweep,'d:', ...
    'LineWidth',1.4,'DisplayName','No S; A and B occur'); hold off;
grid on; xlabel('Pump-A failure probability per mission (dimensionless)');
ylabel('Event probability per mission (dimensionless)');
title('Pump-A lever is conditioned by pump B through the AND gate');
legend('Location','best');
fprintf(['Pump-A sweep Q_top = [%.6f %.6f %.6f %.6f %.6f]\n'], ...
    topEventPumpASweep(1),topEventPumpASweep(2), ...
    topEventPumpASweep(3),topEventPumpASweep(4), ...
    topEventPumpASweep(5));
disp(['Mechanism: qS and qB stay fixed. Changing qA leaves {S} unchanged; ' ...
    'its top-event effect is multiplied by the fixed qB through A AND B.']);

%% Deliberately broken case - replace the pump AND gate with OR
brokenCase = model(0.005,0.10,0.10);
figure('Name','P05 broken case: wrong redundant-pump gate');
bar(1:3,[brokenCase.topEventProbability, ...
    brokenCase.wrongGateTopEventProbability, ...
    brokenCase.sharedCutSetProbability],0.62);
grid on; xticks(1:3);
xticklabels({'Correct: S OR (A AND B)','Broken: S OR A OR B','Shared event S'});
ylabel('Event probability per mission (dimensionless)');
title('Broken gate: one pump failure is falsely declared loss of cooling');

overstatementFactor = brokenCase.wrongGateTopEventProbability/ ...
    brokenCase.topEventProbability;
fprintf(['Broken-case symptom: correct Q_top = %.5f, wrong-OR Q_top = ' ...
    '%.5f, overstatement factor = %.2f.\n'], ...
    brokenCase.topEventProbability, ...
    brokenCase.wrongGateTopEventProbability,overstatementFactor);
assert(brokenCase.wrongGateTopEventProbability > ...
    10*brokenCase.topEventProbability, ...
    'The wrong pump-OR gate should produce a recognizable overstatement.');
assert(~(false || (true && false)) && (false || true || false), ...
    'The broken gate must falsely trigger for S=0, A=1, B=0.');
disp(['Diagnosis: redundancy requires both pump-specific failures. OR ' ...
    'changes the system logic and falsely treats either single pump failure as sufficient.']);

function drawFaultTree(axesHandle,out)
%DRAWFAULTTREE Render the transparent Boolean structure without a toolbox.
cla(axesHandle,'reset'); hold(axesHandle,'on');
plot(axesHandle,[5 5],[8.85 8.15],'k-','LineWidth',1.4);
plot(axesHandle,[5 2.2],[7.75 6.75],'k-','LineWidth',1.4);
plot(axesHandle,[5 7.4],[7.75 6.75],'k-','LineWidth',1.4);
plot(axesHandle,[7.4 6.25],[5.95 4.95],'k-','LineWidth',1.4);
plot(axesHandle,[7.4 8.55],[5.95 4.95],'k-','LineWidth',1.4);

text(axesHandle,5,9.25,sprintf('TOP: cooling unavailable  Q = %.5f', ...
    out.topEventProbability),'HorizontalAlignment','center', ...
    'FontWeight','bold','BackgroundColor',[1.00 0.86 0.82],'Margin',6);
text(axesHandle,5,7.95,'OR','HorizontalAlignment','center', ...
    'FontWeight','bold','BackgroundColor',[0.92 0.92 0.92],'Margin',5);
text(axesHandle,2.2,6.45,sprintf(['S: shared supply lost\n' ...
    'qS = %.3f'],out.sharedSupplyFailureProbability), ...
    'HorizontalAlignment','center','BackgroundColor',[0.86 0.92 1.00], ...
    'Margin',6);
text(axesHandle,7.4,6.25,'AND','HorizontalAlignment','center', ...
    'FontWeight','bold','BackgroundColor',[0.92 0.92 0.92],'Margin',5);
text(axesHandle,6.25,4.65,sprintf(['A: pump A fails\n' ...
    'qA = %.3f'],out.pumpAFailureProbability), ...
    'HorizontalAlignment','center','BackgroundColor',[0.90 0.97 0.90], ...
    'Margin',6);
text(axesHandle,8.55,4.65,sprintf(['B: pump B fails\n' ...
    'qB = %.3f'],out.pumpBFailureProbability), ...
    'HorizontalAlignment','center','BackgroundColor',[0.90 0.97 0.90], ...
    'Margin',6);
text(axesHandle,5,3.25,'Minimal cut sets: {S} and {A,B}', ...
    'HorizontalAlignment','center','FontWeight','bold');
hold(axesHandle,'off'); axis(axesHandle,[0.5 9.8 2.8 9.8]);
axis(axesHandle,'off');
title(axesHandle,'Fault-tree structure and fixed-mission event probabilities');
end
